function ring(cx, cy, rx, ry, start = -1.75, turns = 1.06, steps = 18) {
  const pts = [];
  for (let i = 0; i <= steps; i += 1) {
    const a = start - (i / steps) * Math.PI * 2 * turns;
    pts.push([cx + Math.cos(a) * rx, cy + Math.sin(a) * ry]);
  }
  return pts;
}

