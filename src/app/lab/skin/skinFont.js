export function drawDigit(ctx, ch, x, y, on, off) {
  const lit = DIGITS[ch] ?? "";
  for (const k of Object.keys(SEG)) {
    const [sx, sy, w, h] = SEG[k];
    ctx.fillStyle = lit.includes(k) ? on : off;
    ctx.fillRect(x + sx, y + sy, w, h);
  }
}
