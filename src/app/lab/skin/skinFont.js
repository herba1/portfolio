const norm = (ch) => {
  const up = ch.toUpperCase();
  if (G[up]) return up;
  if (ch === "’" || ch === "‘") return "'";
  return " ";
};

export function textWidth(str) {
  let w = 0;
  for (const ch of str) w += G[norm(ch)][0].length + 1;
  return Math.max(0, w - 1);
}

export function drawText(ctx, str, x, y, color) {
  ctx.fillStyle = color;
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (const ch of str) {
    const g = G[norm(ch)];
    for (let r = 0; r < 5; r += 1) {
      const row = g[r];
      for (let c = 0; c < row.length; c += 1) if (row[c] === "#") ctx.fillRect(cx + c, cy + r, 1, 1);
    }
    cx += g[0].length + 1;
  }
  return cx;
}

export function fitText(str, max) {
  if (textWidth(str) <= max) return str;
  let s = str;
  while (s.length > 1 && textWidth(`${s}..`) > max) s = s.slice(0, -1);
  return `${s.trimEnd()}..`;
}

