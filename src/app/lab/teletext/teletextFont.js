const CELL_W = 12;
const CELL_H = 20;
const cache = new Map();

function bitsFor(rows) {
  const on = (x, y) => y >= 0 && y < 10 && x >= 0 && x < 6 && rows[y - 1] && rows[y - 1][x] === "#";
  const out = new Uint8Array(CELL_W * CELL_H);
  for (let y = 0; y < 10; y += 1) {
    for (let x = 0; x < 6; x += 1) {
      if (on(x, y)) {
        out[y * 2 * CELL_W + x * 2] = 1;
        out[y * 2 * CELL_W + x * 2 + 1] = 1;
        out[(y * 2 + 1) * CELL_W + x * 2] = 1;
        out[(y * 2 + 1) * CELL_W + x * 2 + 1] = 1;
        continue;
      }
      for (const dx of [-1, 1]) {
        for (const dy of [-1, 1]) {
          if (on(x + dx, y) && on(x, y + dy) && !on(x + dx, y + dy)) {
            const px = x * 2 + (dx < 0 ? 0 : 1);
            const py = y * 2 + (dy < 0 ? 0 : 1);
            out[py * CELL_W + px] = 1;
          }
        }
      }
    }
  }
  return out;
}

export function glyphBits(ch) {
  if (cache.has(ch)) return cache.get(ch);
  let rows = G[ch];
  if (!rows) {
    const folded = ch.normalize("NFD").replace(/[\u0300-\u036f]/g, "");
    rows = G[folded] || (ch === "\u2019" || ch === "\u2018" ? G["'"] : G[" "]);
  }
  const bits = bitsFor(rows);
  cache.set(ch, bits);
  return bits;
}

export { CELL_W, CELL_H };
