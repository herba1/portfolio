export const GLYPH_ROWS = 9;

const cache = new Map();

export function glyph(ch) {
  if (cache.has(ch)) return cache.get(ch);
  let rows = G[ch];
  if (!rows) {
    const folded = ch.normalize("NFD").replace(/[̀-ͯ]/g, "");
    rows = G[folded] || (ch === "’" || ch === "‘" ? G["'"] : ch === "“" || ch === "”" ? G['"'] : ch === "—" || ch === "–" ? G["-"] : G["?"]);
  }
  const w = rows[0].length;
  const bits = new Uint8Array(w * GLYPH_ROWS);
  rows.forEach((row, y) => {
    for (let x = 0; x < w; x += 1) if (row[x] === "#") bits[y * w + x] = 1;
  });
  const g = { w, bits };
  cache.set(ch, g);
  return g;
}

export function hasGlyph(ch) {
  return Boolean(G[ch]);
}

export function rasterize(text) {
  const chars = [...text];
  const spans = [];
  let w = 0;
  chars.forEach((ch, i) => {
    const g = glyph(ch);
    spans.push({ x: w, w: g.w, g });
    w += g.w + (i < chars.length - 1 ? 1 : 0);
  });
  const bits = new Uint8Array(Math.max(1, w) * GLYPH_ROWS);
  for (const s of spans) {
    for (let y = 0; y < GLYPH_ROWS; y += 1) {
      for (let x = 0; x < s.w; x += 1) if (s.g.bits[y * s.w + x]) bits[y * w + s.x + x] = 1;
    }
  }
  return { w, h: GLYPH_ROWS, bits, spans };
}
