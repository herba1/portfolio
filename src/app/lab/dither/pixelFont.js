const COMPILED = new Map();

function compile(ch) {
  if (COMPILED.has(ch)) return COMPILED.get(ch);
  const rows = G[ch];
  let out = null;
  if (rows) {
    const width = Math.max(1, ...rows.map((r) => r.length));
    const pixels = [];
    rows.forEach((r, y) => {
      for (let x = 0; x < r.length; x += 1) if (r[x] === "#") pixels.push(x, y);
    });
    out = { width, pixels };
  }
  COMPILED.set(ch, out);
  return out;
}

export const FONT_ASCENT = 7;
export const FONT_HEIGHT = 9;
const SPACE = 3;

export function hasGlyph(ch) {
  return ch === " " || Boolean(G[ch]);
}

export function charWidth(ch, bold = false) {
  if (ch === " ") return SPACE;
  const g = compile(ch);
  return g ? g.width + (bold ? 1 : 0) : 0;
}

export function measure(text, bold = false) {
  let w = 0;
  const chars = [...text];
  chars.forEach((ch, i) => {
    w += charWidth(ch, bold);
    if (i < chars.length - 1) w += 1;
  });
  return w;
}

export function drawText(plot, x, y, text, bold = false) {
  let cx = x;
  const chars = [...text];
  chars.forEach((ch) => {
    if (ch === " ") {
      cx += SPACE + 1;
      return;
    }
    const g = compile(ch);
    if (!g) return;
    const p = g.pixels;
    for (let i = 0; i < p.length; i += 2) {
      plot(cx + p[i], y + p[i + 1]);
      if (bold) plot(cx + p[i] + 1, y + p[i + 1]);
    }
    cx += g.width + (bold ? 1 : 0) + 1;
  });
  return cx - x - 1;
}
