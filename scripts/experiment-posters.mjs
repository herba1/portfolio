// Stills for the experiments index. Each tile paints its poster on the first
// frame and swaps to the live piece once that has painted, so the poster must
// be the frame the live piece shows at that moment, in its own tile — a still
// of the piece a few seconds in jumps back when the poster lifts. This loads
// the index from a running server and captures each tile as it goes live,
// twice: in the desktop bento, and in the 4:5 tiles a phone stacks (a phone
// crop of the desktop still is a different picture).
//
//   npm run build && npm start   (or npm run dev)
//   node scripts/experiment-posters.mjs [http://localhost:3000] [slug ...]
//   VARIANT=wide node scripts/experiment-posters.mjs ...   (one layout only)
//
// Needs Playwright; it is not a dependency of the site, so a global install
// (npm i -g playwright) is used when the project has none.
import { createRequire } from "node:module";
import { execSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

const require = createRequire(import.meta.url);
let playwright;
try {
  playwright = require("playwright");
} catch {
  playwright = require(join(execSync("npm root -g").toString().trim(), "playwright"));
}

const ROOT = process.cwd();
const OUT_DIR = join(ROOT, "public/posters/experiments");
const MAP = join(ROOT, "src/app/experiments/layouts/posters.js");
const base = process.argv[2]?.startsWith("http") ? process.argv[2] : "http://localhost:3000";
const only = process.argv.slice(process.argv[2]?.startsWith("http") ? 3 : 2).map((slug) => (slug.startsWith("/") ? slug : `/${slug}`));
// Two frames after the poster lifts: what the visitor sees at the handoff.
const HANDOFF_MS = 120;
// Pieces fed live data (recent Spotify tracks) change by the hour, so a still
// of them would never match what mounts. They get no poster.
const LIVE_DATA = new Set(["/deck", "/flyout", "/cover-ring", "/counter", "/one-line", "/taffy", "/stir"]);
const QUALITY = 74;
// The bento below 900px stacks every tile at 4:5; LivePiece serves the narrow
// still there.
const VARIANTS = [
  { key: "wide", viewport: { width: 1440, height: 900 }, scale: 1.5, suffix: "" },
  { key: "narrow", viewport: { width: 390, height: 844 }, scale: 2, suffix: "-narrow", isMobile: true, hasTouch: true },
];

const fileFor = (slug) => slug.replace(/^\//, "").replace(/\//g, "--");

// CHROME_ARGS adds flags, e.g. on a machine without a GPU:
// "--use-angle=swiftshader --enable-gpu-rasterization --enable-gpu-compositing"
const extraArgs = process.env.CHROME_ARGS?.split(" ").filter(Boolean) ?? [];
const launch = () => playwright.chromium.launch({ args: ["--enable-unsafe-swiftshader", "--ignore-gpu-blocklist", ...extraArgs] });
mkdirSync(OUT_DIR, { recursive: true });
const previous = await import(`${MAP}?t=${Date.now()}`).then((mod) => mod.POSTERS).catch(() => ({}));
const posters = { ...previous };
const save = () => {
  const sorted = Object.fromEntries(Object.entries(posters).sort(([a], [b]) => a.localeCompare(b)));
  writeFileSync(MAP, `// Generated by scripts/experiment-posters.mjs — a still per tile, shown until the live piece paints.\nexport const POSTERS = ${JSON.stringify(sorted, null, 2)};\n`);
};

// Each tile gets a fresh browser and a fresh load of the index scrolled to
// it, so the still is that tile's first live frame however long the earlier
// tiles took, and a piece that wedges a (software) GPU costs only its own
// still.
function hideFixed() {
  for (const el of document.body.querySelectorAll("*")) {
    if (el.closest(".xl-bento")) continue;
    if (getComputedStyle(el).position === "fixed") el.style.setProperty("visibility", "hidden", "important");
  }
}

async function capture(variant, index, slug) {
  const browser = await launch();
  try {
    const context = await browser.newContext({ viewport: variant.viewport, deviceScaleFactor: variant.scale, isMobile: variant.isMobile, hasTouch: variant.hasTouch });
    const page = await context.newPage();
    await page.goto(`${base}/experiments`, { waitUntil: "domcontentloaded" });
    // No entrance, and nothing fixed (nav, switcher) over the tiles.
    await page.addStyleTag({ content: ".xl-tile{animation:none!important}" });
    await page.evaluate(hideFixed);
    await page.evaluate((n) => {
      const tile = document.querySelectorAll(".xl-bento .xl-tile")[n];
      const r = tile.getBoundingClientRect();
      window.scrollTo(0, window.scrollY + r.top + r.height / 2 - window.innerHeight / 2);
    }, index);
    const tile = (await page.$$(".xl-bento .xl-tile"))[index];
    await page.waitForFunction((n) => document.querySelectorAll(".xl-bento .xl-tile")[n].querySelector(".xl-live[data-live]"), index, { timeout: 30000 }).catch(() => {});
    await page.waitForTimeout(HANDOFF_MS);
    await page.mouse.move(2, 2);
    // Again: some fixed UI (the dev palette on localhost) only mounts after
    // hydration.
    await page.evaluate(hideFixed);
    // A clip of the page rather than an element shot: a live piece never
    // holds still long enough for an element to count as stable.
    const clip = await (await tile.$(".piece-box")).boundingBox();
    const png = await page.screenshot({ clip, animations: "allow", style: ".xl-live__poster{display:none!important}", timeout: 60000 });
    const meta = await sharp(png).metadata();
    const name = `${fileFor(slug)}${variant.suffix}.webp`;
    const webp = await sharp(png).webp({ quality: QUALITY, smartSubsample: true }).toBuffer();
    writeFileSync(join(OUT_DIR, name), webp);
    const version = createHash("sha256").update(webp).digest("base64url").slice(0, 8);
    const still = { src: `/posters/experiments/${name}?v=${version}`, width: Math.round(meta.width / variant.scale), height: Math.round(meta.height / variant.scale) };
    if (variant.key === "wide") posters[slug] = { ...still, narrow: posters[slug]?.narrow };
    else posters[slug] = { ...posters[slug], narrow: still };
    console.log(`${variant.key.padEnd(7)} ${slug.padEnd(40)} ${(webp.length / 1024).toFixed(0).padStart(4)} KB`);
  } finally {
    await browser.close().catch(() => {});
  }
}

const listing = await launch();
const listPage = await listing.newPage();
await listPage.goto(`${base}/experiments`, { waitUntil: "domcontentloaded" });
const tiles = await listPage.$$eval(".xl-bento .xl-tile", (items) => items.map((item, index) => ({ index, slug: item.dataset.slug })));
await listing.close();

// VARIANT=wide or VARIANT=narrow recaptures one layout only.
for (const variant of VARIANTS.filter((v) => !process.env.VARIANT || v.key === process.env.VARIANT)) {
  for (const { index, slug } of tiles) {
    if (only.length && !only.includes(slug)) continue;
    if (LIVE_DATA.has(slug)) {
      delete posters[slug];
      continue;
    }
    await capture(variant, index, slug).catch((error) => {
      console.warn(`${variant.key.padEnd(7)} ${slug.padEnd(40)} skipped, kept the old still: ${error.message.split("\n")[0]}`);
    });
    save();
  }
}
save();
