// Stills for the experiments index. Each tile paints its poster on the first
// frame and swaps to the live piece once that has painted, so the poster must
// be the piece as it looks live, in its own tile. This loads the index from a
// running server, lets each tile go live, and captures it.
//
//   npm run build && npm start   (or npm run dev)
//   node scripts/experiment-posters.mjs [http://localhost:3000] [slug ...]
//
// Needs Playwright; it is not a dependency of the site, so a global install
// (npm i -g playwright) is used when the project has none.
import { createRequire } from "node:module";
import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

const require = createRequire(import.meta.url);
let playwright;
try {
  playwright = require("playwright");
} catch {
  playwright = require(join(execSync("npm root -g").toString().trim(), "playwright"));
}

const ROOT = process.cwd();
const OUT_DIR = join(ROOT, "public/posters/experiments");
const MAP = join(ROOT, "src/app/experiments/layouts/posters.js");
const base = process.argv[2]?.startsWith("http") ? process.argv[2] : "http://localhost:3000";
const only = process.argv.slice(process.argv[2]?.startsWith("http") ? 3 : 2).map((slug) => (slug.startsWith("/") ? slug : `/${slug}`));
const SETTLE_MS = 2400;
// Pieces fed live data (recent Spotify tracks) change by the hour, so a still
// of them would never match what mounts. They get no poster.
const LIVE_DATA = new Set(["/deck", "/flyout", "/cover-ring", "/ascii-cover", "/counter", "/one-line", "/taffy", "/stir"]);
const WIDTH = 1440;
const HEIGHT = 900;
const SCALE = 1.5;
const QUALITY = 74;

const fileFor = (slug) => slug.replace(/^\//, "").replace(/\//g, "--");

const browser = await playwright.chromium.launch({ args: ["--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const page = await browser.newPage({ viewport: { width: WIDTH, height: HEIGHT }, deviceScaleFactor: SCALE });
await page.goto(`${base}/experiments`, { waitUntil: "networkidle" });
await page.addStyleTag({ content: ".xl-live__poster{display:none!important}.xl-tile{animation:none!important}" });
await page.evaluate(() => {
  for (const el of document.body.querySelectorAll("*")) {
    if (el.closest(".xl-bento")) continue;
    if (getComputedStyle(el).position === "fixed") el.style.setProperty("visibility", "hidden", "important");
  }
});

const tiles = await page.$$eval(".xl-bento .xl-tile", (items) => items.map((item, index) => ({ index, slug: item.dataset.slug })));
mkdirSync(OUT_DIR, { recursive: true });

const previous = await import(`${MAP}?t=${Date.now()}`).then((mod) => mod.POSTERS).catch(() => ({}));
const posters = { ...previous };

for (const { index, slug } of tiles) {
  if (only.length && !only.includes(slug)) continue;
  if (LIVE_DATA.has(slug)) {
    delete posters[slug];
    continue;
  }
  const tile = (await page.$$(".xl-bento .xl-tile"))[index];
  await tile.scrollIntoViewIfNeeded();
  await page.waitForFunction((i) => document.querySelectorAll(".xl-bento .xl-tile")[i].querySelector(".xl-live[data-live]"), index, { timeout: 15000 }).catch(() => {});
  await page.waitForTimeout(SETTLE_MS);
  await page.mouse.move(2, 2);
  const box = await tile.$(".piece-box");
  const png = await box.screenshot({ animations: "allow" });
  const meta = await sharp(png).metadata();
  const name = `${fileFor(slug)}.webp`;
  const webp = await sharp(png).webp({ quality: QUALITY, smartSubsample: true }).toBuffer();
  writeFileSync(join(OUT_DIR, name), webp);
  const version = Buffer.from(webp.subarray(webp.length - 64)).toString("base64url").slice(0, 8);
  posters[slug] = { src: `/posters/experiments/${name}?v=${version}`, width: Math.round(meta.width / SCALE), height: Math.round(meta.height / SCALE) };
  console.log(`${slug.padEnd(40)} ${(webp.length / 1024).toFixed(0).padStart(4)} KB`);
}

const sorted = Object.fromEntries(Object.entries(posters).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(MAP, `// Generated by scripts/experiment-posters.mjs — a still per tile, shown until the live piece paints.\nexport const POSTERS = ${JSON.stringify(sorted, null, 2)};\n`);
await browser.close();
